// lib/models/useful_link_model.dart
import 'package:cloud_firestore/cloud_firestore.dart';

enum LinkType {
  website,
  youtube,
}

class UsefulLink {
  final String id;
  final String name;
  final String url;
  final String iconUrl;
  final LinkType type;
  final DateTime createdAt;
  final int displayOrder;

  UsefulLink({
    required this.id,
    required this.name,
    required this.url,
    required this.iconUrl,
    required this.type,
    required this.createdAt,
    required this.displayOrder,
  });

  /// Convert UsefulLink object to Map for Firestore
  Map<String, dynamic> toMap() {
    return {
      'name': name,
      'url': url,
      'iconUrl': iconUrl,
      'type': type == LinkType.website ? 'website' : 'youtube',
      'createdAt': createdAt,
      'displayOrder': displayOrder,
    };
  }

  /// Create a UsefulLink object from Firestore document
  factory UsefulLink.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>? ?? {};

    // Parse the type string back to LinkType enum
    final typeString = data['type'] as String? ?? 'website';
    final linkType =
        typeString == 'website' ? LinkType.website : LinkType.youtube;

    return UsefulLink(
      id: doc.id,
      name: data['name']?.toString() ?? '',
      url: data['url']?.toString() ?? '',
      iconUrl: data['iconUrl']?.toString() ?? '',
      type: linkType,
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      displayOrder: (data['displayOrder'] is num) ? (data['displayOrder'] as num).toInt() : 0,
    );
  }

  /// Create a copy of the link with updated fields
  UsefulLink copyWith({
    String? id,
    String? name,
    String? url,
    String? iconUrl,
    LinkType? type,
    DateTime? createdAt,
    int? displayOrder,
  }) {
    return UsefulLink(
      id: id ?? this.id,
      name: name ?? this.name,
      url: url ?? this.url,
      iconUrl: iconUrl ?? this.iconUrl,
      type: type ?? this.type,
      createdAt: createdAt ?? this.createdAt,
      displayOrder: displayOrder ?? this.displayOrder,
    );
  }

  /// For creating a new link (without ID) - ID will be generated by Firestore
  factory UsefulLink.forAdd({
    required String name,
    required String url,
    required String iconUrl,
    required LinkType type,
    required int displayOrder,
  }) {
    return UsefulLink(
      id: '', // Empty ID for new documents
      name: name,
      url: url,
      iconUrl: iconUrl,
      type: type,
      createdAt: DateTime.now(),
      displayOrder: displayOrder,
    );
  }

  @override
  String toString() {
    return 'UsefulLink(id: $id, name: $name, type: $type, order: $displayOrder)';
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is UsefulLink &&
        other.id == id &&
        other.name == name &&
        other.url == url &&
        other.iconUrl == iconUrl &&
        other.type == type &&
        other.createdAt == createdAt &&
        other.displayOrder == displayOrder;
  }

  @override
  int get hashCode {
    return Object.hash(id, name, url, iconUrl, type, createdAt, displayOrder);
  }
}
